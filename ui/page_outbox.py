"""Outbox: every vendor email the system generated, newest first."""
from __future__ import annotations

from html import escape

import streamlit as st

from engine import store
from ui import components as C
from ui import metrics, state


def render() -> None:
    st.title("Outbox")
    st.caption("Generated vendor emails stay in PayeeTrail's outbox; nothing is sent automatically.")
    runs = [r for r in store.all_runs() if r.get("email")]
    if not runs:
        st.info("No runs yet. Go to Submit & Verify and load a demo scenario.")
        st.button("Go to Submit & Verify", key="btn_outbox_go", type="primary",
                  on_click=state.cb_goto, args=("Submit & Verify",))
        return

    statuses = st.multiselect("Status", metrics.STATUSES, key="ui_outbox_status", placeholder="All statuses")
    shown = [r for r in runs if not statuses or r["status"] in statuses]
    st.caption(f"{len(shown)} email(s)")
    for r in shown:
        email = r["email"]
        label = f"{C.STATUS_ICON.get(r['status'], '')} {r['status']} · {C.md_safe(email['subject'])}"
        with st.expander(label):
            meta, go = st.columns([6, 1], vertical_alignment="center")
            queue = escape(str(r["queue"]), quote=True)
            recipient = escape(str(email.get("to") or "(none)"), quote=True)
            reference = escape(str(r["submission_ref"]), quote=True)
            created_at = escape(str(r["created_at"]).replace("T", " "), quote=True)
            generated_by = escape(str(email.get("polished_by", "template")), quote=True)
            meta.markdown(
                f"{C.status_pill(r['status'])}<span class='vg-queue'>{queue}</span><br>"
                f"<span class='vg-muted'>To <code>{recipient}</code> · "
                f"<code>{reference}</code> v{r['version']} · run #{r['run_id']} · "
                f"{created_at} · generated by {generated_by}</span>",
                unsafe_allow_html=True)
            go.button("Open run", key=f"o_open_{r['run_id']}", on_click=state.cb_goto,
                      args=("Run detail", r["run_id"]), width="stretch")
            st.code(email["body"], language=None, wrap_lines=True)
            if email.get("polish_error"):
                st.warning(email["polish_error"] + " The deterministic template remains unchanged.")
            if email.get("polish_suggestion"):
                st.warning("An unapproved LLM draft is available; the template above remains the message of record.")
                with st.expander(f"Review {email.get('polish_model', 'LLM')} draft"):
                    st.text(email["polish_suggestion"])
